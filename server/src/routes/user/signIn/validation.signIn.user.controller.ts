import z from 'zod';

import { createZod, v } from '@nono-art/validation';

import type { B, P, Q } from './types.signIn.user.controller';

/* -------------------------------------------------------------------------- */
/*                                   PARAMS                                   */
/* -------------------------------------------------------------------------- */

export const paramsValidator: z.ZodType<P> = v.common.strictEmptyObject;

/* -------------------------------------------------------------------------- */
/*                                  / PARAMS                                  */
/* -------------------------------------------------------------------------- */

/* -------------------------------------------------------------------------- */
/*                                    QUERY                                   */
/* -------------------------------------------------------------------------- */

export const queryValidator: z.ZodType<Q> = v.common.emptyObject;

/* -------------------------------------------------------------------------- */
/*                                   / QUERY                                  */
/* -------------------------------------------------------------------------- */

/* -------------------------------------------------------------------------- */
/*                                    BODY                                    */
/* -------------------------------------------------------------------------- */

export const bodyValidator: z.ZodType<B> = createZod<B>()(
  z
    .object({
      login: v.user.login,
      password: v.user.password,
    })
    .strict()
    .required(),
);

/* -------------------------------------------------------------------------- */
/*                                   / BODY                                   */
/* -------------------------------------------------------------------------- */
