/* -------------------------------------------------------------------------- */

/* -------------------------------------------------------------------------- */
/*                                   STYLES                                   */
/* -------------------------------------------------------------------------- */

const styles = StyleSheet.create({
  hr: {
    height: StyleSheet.hairlineWidth,
    width: '98%',
  },
  color: {
    backgroundColor: color.grey800,
  },
  margin: {
    marginVertical: 7,
  },
});

