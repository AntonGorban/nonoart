import React from 'react';

/* -------------------------------------------------------------------------- */
/*                                  COMPONENT                                 */
/* -------------------------------------------------------------------------- */

export const MultilineText = React.memo<Props>(({ children }) => (
  <>
    {children.split('\n').map((text, i) => (
      <React.Fragment key={i}>
        {i !== 0 && <br />}
        {text}
      </React.Fragment>
    ))}
  </>
));

/* -------------------------------------------------------------------------- */
/*                                 / COMPONENT                                */
/* -------------------------------------------------------------------------- */

/* -------------------------------------------------------------------------- */
/*                                    TYPES                                   */
/* -------------------------------------------------------------------------- */

interface Props {
  readonly children: string;
}

